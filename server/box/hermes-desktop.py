"""Bot HQ adapter for Hermes' local Bot Desktop. Run with Hermes' Python:
<hermes-python> -I /path/to/hermes-desktop.py <action> [arguments]

HERMES_HOME selects the bot. RFB stays on Hermes' private Unix socket; only
the authenticated Bot HQ server can reach this stdio bridge.
"""
from __future__ import annotations

import json
import os
import selectors
import signal
import socket
import subprocess
import sys
import time


def emit(value):
    print(json.dumps(value), flush=True)


def main():
    from tools.bot_desktop import lease, placement, runtime

    action = sys.argv[1]
    if action == "status":
        emit(runtime.status().as_dict())
        return
    if placement.resolve().where != placement.GATEWAY:
        raise RuntimeError("Bot HQ's hermes backend requires a desktop on this PC. Configure terminal.backend: local for this bot.")
    if action == "start":
        emit(runtime.start().as_dict())
    elif action == "stop":
        if lease.release(unless_human=True).holder == lease.HUMAN:
            raise RuntimeError("A person has control of this desktop. Hand control back before stopping it.")
        runtime.stop()
        emit({"ok": True})
    elif action == "screenshot":
        from tools.bot_desktop.thumbnail import thumbnail_data_url
        emit({"image": thumbnail_data_url()})
    elif action == "terminal":
        from tools.bot_desktop import runtime
        runtime.start()
        # argv, not shell interpolation; the command itself is generated by Bot HQ.
        subprocess.Popen(["xfce4-terminal", "--disable-server", "--hold", "--title", sys.argv[3],
                          "--command", "bash -lc " + __import__("shlex").quote(sys.argv[2])],
                         env=runtime.desktop_env(dict(os.environ)), start_new_session=True,
                         stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        emit({"ok": True})
    elif action == "relay":
        relay(sys.argv[2], sys.argv[3], runtime, lease)
    else:
        raise ValueError("Unknown desktop action")


def relay(mode, viewer_id, runtime, lease):
    if mode not in ("watch", "control"):
        raise ValueError("Unknown viewer mode")
    state = runtime.status()
    if not state.running or not state.socket:
        raise RuntimeError("The bot's desktop is not running")
    # Prevent concurrent human input and Hermes computer/browser actions.
    if mode == "control":
        lease.acquire(viewer_id, reason="Bot HQ viewer")
    signal.signal(signal.SIGTERM, lambda *_: sys.exit(0))
    try:
        with socket.socket(socket.AF_UNIX) as upstream, selectors.DefaultSelector() as sel:
            upstream.connect(state.socket)
            sel.register(upstream, selectors.EVENT_READ)
            sel.register(sys.stdin.buffer, selectors.EVENT_READ)
            touched = 0.0
            while True:
                if mode == "control" and not lease.viewer_may_send_input(viewer_id):
                    return  # another viewer took over; release() below respects their ownership
                if time.monotonic() - touched > 10:
                    runtime.touch_activity()
                    touched = time.monotonic()
                for key, _ in sel.select(timeout=0.25):
                    if key.fileobj is upstream:
                        data = upstream.recv(65536)
                        if not data:
                            return
                        sys.stdout.buffer.write(data)
                        sys.stdout.buffer.flush()
                    else:
                        data = os.read(sys.stdin.fileno(), 65536)
                        if not data:
                            return
                        if mode == "control" and not lease.viewer_may_send_input(viewer_id):
                            return
                        upstream.sendall(data)
    finally:
        if mode == "control":
            lease.release(viewer_id)


if __name__ == "__main__":
    try:
        # Managed Hermes installations lease their dependencies through bootstrap.
        # Conventional virtualenv installs already carry those dependencies.
        source = os.environ.get("HERMES_SOURCE_DIR", os.path.expanduser("~/.hermes/hermes-agent"))
        sys.path.insert(0, source)
        if os.path.isfile(os.path.join(source, "hermes_bootstrap.py")):
            __import__("hermes_bootstrap")
        main()
    except Exception as exc:
        print(str(exc), file=sys.stderr, flush=True)
        sys.exit(1)
